"""Generate the strategy version of Trend & Setups from the indicator source.

One source of truth: pine/trend_setups.pine. This tool produces pine/trend_setups_strategy.pine by
  1. replacing the line tagged `// @header` with a strategy() declaration,
  2. sizing from live strategy equity (line tagged `// @equity`),
  3. dropping the block between `// @indicator-only begin` and `// @indicator-only end`
     (alertcondition() is not allowed in strategies),
  4. appending the order logic, which fires on exactly the indicator's entry/exit bars.

Run from research/:  python3 -m tools.build_strategy
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "pine" / "trend_setups.pine"
DST = ROOT / "pine" / "trend_setups_strategy.pine"

HEADER = ('strategy("Trend & Setups — strategy", shorttitle = "T&S strategy", overlay = true, precision = 2, '
          'max_bars_back = 2000, max_labels_count = 500, max_lines_count = 100, initial_capital = 10000, '
          'default_qty_type = strategy.fixed, default_qty_value = 1, process_orders_on_close = true, '
          'commission_type = strategy.commission.percent, commission_value = 0.02, slippage = 1, pyramiding = 0)')

ORDERS = """
// ───── Strategy orders (generated by research/tools/build_strategy.py — edit the indicator, not this file) ─────
// Orders fill at the close of the signal bar (process_orders_on_close), exactly where the indicator signals.
// Size = live strategy equity × risk % ÷ (entry − stop); S3 reversals use half size.
if newEntry > 0 and conf and shares > 0
    strategy.entry("Long", strategy.long, qty = shares, comment = setupName)
if exited and conf
    strategy.close("Long", comment = exitText)
"""


def build(src: str) -> str:
    out, skipping, saw_header, saw_equity = [], False, False, False
    for line in src.splitlines():
        if "// @indicator-only begin" in line:
            skipping = True
            continue
        if "// @indicator-only end" in line:
            skipping = False
            continue
        if skipping:
            continue
        if line.rstrip().endswith("// @header"):
            out.append(HEADER)
            saw_header = True
            continue
        if line.rstrip().endswith("// @equity"):
            out.append("float equityNow = strategy.equity // sized from live strategy equity")
            saw_equity = True
            continue
        if line.startswith("// Strategy version:"):
            out.append("// GENERATED FILE — built from pine/trend_setups.pine by research/tools/build_strategy.py. Do not edit.")
            continue
        out.append(line)
    if not (saw_header and saw_equity) or skipping:
        raise ValueError("indicator source is missing @header / @equity markers or an unclosed @indicator-only block")
    return "\n".join(out).rstrip() + "\n" + ORDERS


def main() -> None:
    DST.write_text(build(SRC.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
